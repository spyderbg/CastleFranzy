// ** Main Class - EvMouseMove
// ////////////////////////////////////////////////////////
class EvMouseMove : public IEvent
{
// ** Members
// ////////////////////////////////////////////////////////
public:
	Coord				x, y;


// ** Ctors / Dtor
// ////////////////////////////////////////////////////////
public:
						EvMouseMove(Coord _x, Coord _y)
							: IEvent(Events::MOUSE_MOVE), x(_x), y(_y)
						{};

	virtual				~EvMouseMove() {};
};



// ** Main Class - EvMouseButton
// ////////////////////////////////////////////////////////
class EvMouseButton : public IEvent
{
// ** Enums
// ////////////////////////////////////////////////////////
public:
	enum MouseButtons
	{
		LEFT = 0,
		MIDDLE,
		RIGHT,
		THUMB,
		WHEEL,
	};


// ** Members
// ////////////////////////////////////////////////////////
public:
	int					id;
	bool				pressed;
	Coord				x, y;


// ** Ctors / Dtor
// ////////////////////////////////////////////////////////
public:
						EvMouseButton(int _id, bool bPressed, Coord _x, Coord _y)
							: IEvent(Events::MOUSE_BUTTON), id(_id), pressed(bPressed), x(_x), y(_y)
						{};

	virtual				~EvMouseButton() {};
};



// ** Main Class - EvMouseWheel
// ////////////////////////////////////////////////////////
class EvMouseWheel : public IEvent
{
// ** Members
// ////////////////////////////////////////////////////////
public:
	int					delta;


// ** Ctors / Dtor
// ////////////////////////////////////////////////////////
public:
						EvMouseWheel(int _delta) : IEvent(Events::MOUSE_WHEEL), delta(_delta) {};
	virtual				~EvMouseWheel() {};
};

