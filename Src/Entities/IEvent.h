// IEvent
//
//		An event dispatched by the EventManager
//
// /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#pragma once

///////////////////////////////////////////////////////////////////////


// ** Main Interface
// ////////////////////////////////////////////////////////
class IEvent
{
// ** Typedefs
// ////////////////////////////////////////////////////////
public:
	typedef int					ID;


// ** Members
// ////////////////////////////////////////////////////////
protected:
	ID							m_id;


// ** Ctors / Dtor
// ////////////////////////////////////////////////////////
protected:
								IEvent(ID id) : m_id(id)	{};
public:
	virtual						~IEvent()					{};

public:
	virtual ID					getEventID() const	{return m_id;};	// must be unique, as it is what the EventManager will use
																	// to know which list of subscribers to use.
};


