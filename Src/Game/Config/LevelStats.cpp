CLevelStats::CLevelStats()
{
	reset();
}

CLevelStats::~CLevelStats()
{
}

void CLevelStats::reset()
{
	Gold = 0;
	Souls = 0;

	for (int i = 0; i < WT_Count; i++)
	{
		WeaponLevel[i] = WL_None;
		WeaponAvailable[i] = true;
	}

	SpellAvailable = ST_None;

	Kills = 0;
}

