// /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Point2D<T>
//
//		Handles a point in a 2D space
//
// /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#ifndef UTILS_POINT2D_H
#define UTILS_POINT2D_H
#include <math.h>



template <typename T>
class Point2D
{
// ** Members
// ////////////////////////////////////////////////////////
public:
	union
	{
		struct {T x, y;};
		T v[2];
	};


// ** Ctors / Dtor
// ////////////////////////////////////////////////////////
public:
					Point2D()						: x(0), y(0)			{};
					Point2D(T _x, T _y)				: x(_x), y(_y)			{};
					Point2D(const Point2D<T>& ref)	: x(ref.x), y(ref.y)	{};
	virtual			~Point2D()												{};


// ** Operators
// ////////////////////////////////////////////////////////
public:
	Point2D<T>&		operator =(const Point2D<T>& ref)			{x=ref.x; y=ref.y; return *this;};
	Point2D<T>&		operator +=(const Point2D<T>& ref)			{x+=ref.x; y+=ref.y; return *this;};
	Point2D<T>&		operator -=(const Point2D<T>& ref)			{x-=ref.x; y-=ref.y; return *this;};

	Point2D<T>		operator +(const Point2D<T>& ref)	const	{return Point2D<T>(x+ref.x, y+ref.y);};
	Point2D<T>		operator -(const Point2D<T>& ref)	const	{return Point2D<T>(x-ref.x, y-ref.y);};


// ** Methods
// ////////////////////////////////////////////////////////
public:
	T				distance(const Point2D<T>& ref)		const	{return sqrt(ref.x*x + ref.y*y);};
	T				distanceSq(const Point2D<T>& ref)	const	{return ref.x*x + ref.y*y;};

	void			set(T _x, T _y)								{x=_x; y=_y;};
};


// /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Implementation /////////////////////////////////////////////////////////////////////////////////////////////////////////
// /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////



#endif