#pragma once

///////////////////////////////////////////////////////////////////////

#include <math.h>

///////////////////////////////////////////////////////////////////////

class Float
{
// ** Constants
// ////////////////////////////////////////////////////////
public:
	static const float			PI;
	static const float			HALF_PI;
	static const float			EPSILON;
	static const float			TO_DEGREE_FACTOR;
	static const float			TO_RADIAN_FACTOR;


// ** Static Methods
// ////////////////////////////////////////////////////////
public:
	static inline bool			areEquals(float v1, float v2)	{return fabs(v1 - v2) < EPSILON;};
	static inline float			toDegree(float rad)				{return rad * TO_DEGREE_FACTOR;};
	static inline float			toRadian(float deg)				{return deg * TO_RADIAN_FACTOR;};
};



