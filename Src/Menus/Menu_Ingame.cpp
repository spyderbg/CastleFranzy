void Menu_Ingame::DoMenuInitializations()
{
	CPlayfield::GetInstance()->DisableIngameTouchInput();

	GainFocus();

	MakeControls();	
}

//---------------------------------------------------------------------------------------------------------
//---------------------------------------------------------------------------------------------------------

void Menu_Ingame::DeleteControls()
{
	VisualControls_Free();
}

void Menu_Ingame::MakeControls()
{
	DeleteControls();

	switch ( m_menuType ) 
	{	
	case IngameMenuPause: CreatePauseMenu(); break;
	case IngameMenuVictory: CreateVictoryMenu(); break;
	case IngameMenuDefeated: CreateDefeatedMenu(); break;
	case IngameMenuHighScore: CreateHighScoreMenu(); break;
	case IngameMenuNotSpecified: /* Empty menu */ break;
	default: GX_ASSERT( false ); break;
	};
}

void Menu_Ingame::ReturnControlToGame()
{	
	LoseFocus();

	CPlayfield::GetInstance()->EnableIngameTouchInput();

	SetMenuType( IngameMenuNotSpecified );

	DeleteControls();

	ShowMenu( false );
}

bool Menu_Ingame::IsOnFocus() 
{ 
	return m_isOnFocus || m_menuConfirmation->IsOnFocus(); 
}


