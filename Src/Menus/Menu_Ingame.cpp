void Menu_Ingame::VisualControlDoAction( IVisualControl* visual_control, int action_id )
{
	switch ( m_menuType ) 
	{	
	case IngameMenuPause:
		DoActionPause( visual_control, action_id );
		break;
	case IngameMenuVictory:
		DoActionVictory( visual_control, action_id );
		break;
	case IngameMenuDefeated:
		DoActionDefeated( visual_control, action_id );
		break;
	case IngameMenuHighScore:
		DoActionHighScore( visual_control, action_id );
		break;
	case IngameMenuNotSpecified:
		break;
	default:
		GX_ASSERT( false );
		break;
	};
}

void Menu_Ingame::DoActionPause( IVisualControl* visual_control, int action_id )
{
	switch ( action_id ) 
	{
	case pause_action_continue: 
		{
			Application::GetInstance()->ShowStatusBar( false );
			Transition_Start( transition_hide, pause_action_continue_trans );
		}
		break;
	case pause_action_continue_trans:
		{
			ReturnControlToGame();
			m_Playfield->SetPlayState( CPlayfield::PS_ExitIGM );
		}
		break;

	case pause_action_sound_options:
		{
			Application::GetInstance()->ShowStatusBar( false );
			Transition_Start( transition_hide, pause_action_sound_options_trans );
		}
		break;
	case pause_action_sound_options_trans:
		{
			GetSoundOptions()->SetIsMenuIngame( true );
			SubMenu_Change("Menu_SoundOptions");
		}
		break;

	case pause_action_help_book:
		{
			Application::GetInstance()->ShowStatusBar( false );
			Transition_Start( transition_hide, pause_action_help_book_trans );
		}
		break;
	case pause_action_help_book_trans:
		{
			GetSoundOptions()->SetIsMenuIngame( true );
			SubMenu_Change( "Menu_Ingame_Help" );
		}
		break;

	case pause_action_exit:
		{
			//SaveFrameStats();
			m_menuConfirmation->SetConfirmationText( _TXT_ID(MENU_INGAME_EXIT_CONFIRM) );
			SubMenu_Change( "Menu_Confirmation" );
		}
		break;
	
	case action_toggle: 
		{
			Transition_Start( transition_hide, action_toggle_trans );
		}
		break;
	case action_toggle_trans: 
		{

		}
		break;
	case pause_action_back:
		{
			Application::GetInstance()->ShowStatusBar( false );
			Transition_Start( transition_hide, pause_action_back_trans );
		}
		break;
	case pause_action_back_trans:
		{
			ReturnControlToGame();
			m_Playfield->SetPlayState( CPlayfield::PS_ExitIGM );
		}
		break;
	}
}

void Menu_Ingame::DoActionVictory( IVisualControl* visual_control, int action_id )
{
	switch ( action_id ) 
	{
	case victory_action_next_level:
		{
			Transition_Start( transition_hide, victory_action_next_level_trans );
		}
		break;
	case victory_action_next_level_trans:
		{
			CPlayfield::GetInstance()->ResumeMusic();
			CPlayfield::GetInstance()->SetPlayState( CPlayfield::PS_Restart );
			this->LoseFocus();
			CPlayfield::GetInstance()->EnableIngameTouchInput();
		}
		break;

	case victory_action_shop: 
		{
			Transition_Start( transition_hide, victory_action_shop_trans );
		}
		break;
	case victory_action_shop_trans:
		{
			CPlayfield::GetInstance()->EnableIngameTouchInput();

			//m_Playfield->SetPlayState( CPlayfield::PS_Shop );
			__MGR_STATES()->switchState<GS_Shop>();
		}
		break;

	case victory_action_exit:
		{
			if( !CPlayfield::GetInstance()->IsLevelOver() )
			{
				m_menuConfirmation->SetConfirmationText( _TXT_ID(MENU_INGAME_EXIT_CONFIRM) );
				SubMenu_Change( "Menu_Confirmation" );
			}
			else
			{
				m_exit = true;
			}
		}
		break;
	};
}

