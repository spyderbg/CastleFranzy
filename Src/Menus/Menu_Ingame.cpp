void Menu_Ingame::DrawBackground()
{
	IVideoDriver *driver = __IRR_DRIVER();	

	int left_x = BORDER_LEFT_X, right_x = BORDER_RIGHT_X;
	int left_y = BORDER_LEFT_Y, right_y = BORDER_RIGHT_Y;
	int titleFrame = MENU_F_MENU_INGAME_TITLE;

	if (m_menuType == IngameMenuHighScore)
	{
		left_x -= 43;
		right_x += 43;
		titleFrame = MENU_F_MENU_INGAME_TITLE_SCORE;
	}

	driver->draw2DRectangle( BACKGROUND_WHOLE_SCREEN, r2i( 0, 0, GAME_SCREEN_W,GAME_SCREEN_H ) );
	//draws opaque quad
	if ( !m_menuHelp->IsOnFocus() ) 
		driver->draw2DRectangle( BACKGROUND_COLOR, r2i(left_x, left_y, right_x, right_y));

	//draws title frame
	m_sprite->PaintFrame( titleFrame, BACKGROUND_TITLE_FRAME_X , BACKGROUND_TITLE_FRAME_Y );

	if ( !m_menuHelp->IsOnFocus() ) 
	{
		//draws arrows
		m_sprite->PaintFrame( BORDER_FRAME_DRIGHT, right_x, right_y );	
		m_sprite->PaintFrame( BORDER_FRAME_DLEFT , left_x, right_y );	
	}

	//draws title text
	m_titleText->Draw();
}

struct SingleScore
{
	int frame;
	const wchar_t* text;
	int value;
	int multiplier;
};

void DrawScores (ASprite* sprite, int x, int* y, r2i backgroundRect, int* total, SingleScore* scores, int scoresCount, int alpha)
{
	int yStep = 40 + (5 - (scoresCount + 1)) * 40 / (scoresCount);
	for (int i = 0; i < scoresCount; ++i)
	{
		sprite->PaintFrame(scores[i].frame, x + 38, *y, alpha);
		__FONT("Arial")->DrawString(scores[i].text, x + 60, *y, CFont::VCENTER|CFont::LEFT, alpha);

		int mul = scores[i].multiplier == 0 ? 1 : scores[i].multiplier;
		if (scores[i].multiplier != 0)
		{
			__FONT("SingleHighScore")->DrawString(FormatNumber(scores[i].value).c_str(), x + 130, *y, CFont::VCENTER|CFont::LEFT, alpha);
			stringw str = FormatString(L"x%s", FormatNumber(scores[i].multiplier).c_str());
			__FONT("SingleHighScore")->DrawString(str.c_str(), x + 220, *y, CFont::VCENTER|CFont::LEFT, alpha);
		}
		__FONT("SingleHighScore")->DrawString(FormatNumber(scores[i].value * mul).c_str(), x + backgroundRect.getWidth() - 20, *y, CFont::VCENTER|CFont::RIGHT, alpha);
		*total += scores[i].value * mul;
		*y += yStep;
	}
}

float Pulse (float t, float maxT, int pulses)
{
	return 0.5f - 0.5f * cosf(t * 2.0f * PI * pulses / maxT);
}

