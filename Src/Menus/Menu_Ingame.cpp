void Menu_Ingame::Update( float dt )
{
	if ( !m_menuShow )
		return;

	m_time += dt;

	UpdateMenuMusic();

	IMenu::Update( dt );

	//if (Transition_IsGoing())
	//	return;

	//handle confirmation
	if( m_menuConfirmation->IsOnFocus() && m_menuConfirmation->GetDialogResult() != RESULT_NONE)
	{
		SubMenu_Remove();
		if(m_menuConfirmation->GetDialogResult() == RESULT_YES)
		{
			m_exit = true;

			///// Cheack achievement "Lock & Load"
			//CLevelStats & stats = CPlayfield::GetInstance()->GetLevelStats();

			//s32 i = 0;
			//while( i < WT_Count && stats.WeaponLevel[i] == (WL_Count-1) ) i++;

			//if( i == WT_Count )
			//	__ACHIEVEMENTS()->setAchieved( "Lock & Load" ); 
		}
	}

	//handle options return 
	if( (m_menuSoundOptions->IsOnFocus() && m_menuSoundOptions->isBack()) || 
		(m_menuIngameHelp->IsOnFocus() && m_menuIngameHelp->isBack()) )
	{
		SubMenu_Remove();
		switch ( m_menuType ) 
		{
		case IngameMenuPause:
			Application::GetInstance()->ShowStatusBar( true );
			GetTitleTextControl()->SetText( k_ingame_pause_title );
			break; 
		case IngameMenuVictory: 
			GetTitleTextControl()->SetText( k_ingame_victory_title );
			break;
		case IngameMenuDefeated:
			GetTitleTextControl()->SetText( k_ingame_defeated_title );
			break;
		}
	}

	/// Cheat codes
	UpdateCheats();

	bool goToLogin = false;
	bool goToSelectLevel = false;

	if (m_menuType == IngameMenuHighScore && m_time > 1.0f && m_touch.IsActive())
	{
		m_exit = true;
		goToLogin = CPlayfield::GetInstance()->m_isEndless && LastScoreWasHighScore();
		goToSelectLevel = !CPlayfield::GetInstance()->m_isEndless;
	}

	if( m_exit )
	{
		Application::GetInstance()->ShowStatusBar( false );

		__ACHIEVEMENTS()->saveAchievementsByProfile( "Player1" );

		if( goToLogin )
			__MGR_STATES()->switchState<GS_Menu>()->GoToLogin();
		else if( goToSelectLevel )
			__MGR_STATES()->switchState<GS_Menu>()->GoToSelectLevel();
		else
			__MGR_STATES()->switchState<GS_Menu>();
	}
}


