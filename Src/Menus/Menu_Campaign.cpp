//---------------------------------------------------------------------------------------------------------
// Perform Visual control actions
//----------------------------------------------------------------------------------------------------------
void Menu_Campaign::VisualControlDoAction( IVisualControl* visual_control, int action_id )
{
	int levelCount = getNumberOfDaysPerLevel().size() - 1;

	switch ( action_id ) 
	{
	case button_action_lose_focus:
		{
			int actionId = visual_control->GetActionId();
			if (actionId >= k_buttons_base_action && actionId < k_buttons_base_action + levelCount)
			{
				visual_control->GetTouchElement()->ReassignTouchTo( m_vpane->GetTouchElement() );
			}
		}
		break;
	case action_back:
		{
			Transition_Start( transition_hide, action_back_trans );
		}
		break;
	case action_back_trans:
		{
			GetParent()->SubMenu_Change( "Menu_NewGame" );
		}		
		break;
	case action_transition:
		{
			CPlayfield::GetInstance()->StartNewLevel( CPlayfield::GetInstance()->m_CurrentLevel );
			return;
		}
	case action_vpane:
		{
		}
		break;

	case action_up:
	case action_down:
		{
		}
		break;
	};

	//handle level buttons
	for ( int i = 0; i < levelCount; i++ ) 
	{
		//handle click logic
		if ( ( i ) + k_buttons_base_action == action_id )
		{
			if( CPlayfield::GetInstance()->m_CurrentDay > 0 )
			{
				m_menuConfirmation->SetConfirmationText( STRING_IDS::MENU_NEW_GAME_WARNING );
				m_menuConfirmation->SetBackGroundFrame( MENU_F_MENU_DIFF_CONFIRMATION_BKG );
				SubMenu_Change( "Menu_Confirmation" );
			}

			m_selected = ( action_id - k_buttons_base_action );

			break;
		}
	}
}

