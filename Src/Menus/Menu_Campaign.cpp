//---------------------------------------------------------------------------------------------------------
void Menu_Campaign::Update( float dt )
{
	if( !m_isInitialized )
		return;

	if (m_arrowUp->IsPressed())
		m_vpane->ScrollVertical(-1);
	
	if (m_arrowDown->IsPressed())
		m_vpane->ScrollVertical(1);

	IMenu::Update( dt );

	if (Transition_IsGoing())
		return;
	
	s32 select = -1;
	
	if( m_selected != -1 )
	{
		if( m_menuConfirmation->IsOnFocus() )			
		{
			if( m_menuConfirmation->GetDialogResult() != RESULT_NONE )
			{
				m_menuConfirmation->SetBackGroundFrame( MENU_F_MENU_CONFIRMATION_BKG );
				SubMenu_Remove();

				if( m_menuConfirmation->GetDialogResult() == RESULT_YES )
				{
					select = m_selected;
				}

				m_selected = -1;
			}
		}
		else
		{
			select = m_selected;
		}
	}

	if( select != -1 )
	{
		m_selected = -1;
		CPlayfield::GetInstance()->m_CurrentLevel =  select;
		Transition_Start( transition_hide, action_transition );				
	}
}

