void Menu_Campaign::Destroy()
{
	if (m_music_id != -1) 
		__MGR_SOUNDS()->stop( m_music_id );

	VisualControls_Free();
	m_isInitialized = false;
	
	// Destroy sub-menus
	//-------------------------------
	SubMenus_Destroy();

	FreeResources();
}

