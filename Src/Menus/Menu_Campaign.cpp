void Menu_Campaign::GainFocus()
{
	IMenu::GainFocus();

	/// Set unlocked levels
	array<int> daysPerLevel = getNumberOfDaysPerLevel();

	for ( int i = 0; i < daysPerLevel.size() - 1; i++ )
	{		
		if( i <= CPlayfield::GetInstance()->UnlockLevel( CPlayfield::GetInstance()->getDifficulty() ) || CGameConfig::UnlockAllLevels )
			VisualControlGetByActionId( k_buttons_base_action + i )->SetEnabled( true );
		else 
			VisualControlGetByActionId( k_buttons_base_action + i )->SetEnabled( false );
	}

	m_vpane->ReturnToStartPos();

	m_selected = -1;
}

