//---------------------------------------------------------------------------------------------------------
// Perform Visual control actions
//---------------------------------------------------------------------------------------------------------
void Menu_GameSettings::VisualControlDoAction( IVisualControl* visual_control, int action_id )
{
	CPlayfield* playfield = CPlayfield::GetInstance();

	switch ( action_id ) 
	{
	case action_screen_orientation_lock:	
		{
			Application::GetInstance()->m_deviceOrientationLocked = !Application::GetInstance()->m_deviceOrientationLocked;
			CUserProfile profile = __PROFILE();				
			profile.Set( "ScreenOrientationLock", (int)Application::GetInstance()->m_deviceOrientationLocked );

			if ( Application::GetInstance()->m_deviceOrientationLocked ) 
			{
				m_buttonLock->SetAnimations( m_sprite, 3, k_button_scren_orientation_lock_anim_normal_on, k_button_scren_orientation_lock_anim_pressed_on, k_button_scren_orientation_lock_anim_blink_on );
				m_buttonLock->SetText2( k_button_scren_orientation_lock_text2, k_button_scren_orientation_lock_font1, k_button_scren_orientation_lock_font2 );
			}
			else 
			{
				m_buttonLock->SetAnimations( m_sprite, 3, k_button_scren_orientation_lock_anim_normal_off, k_button_scren_orientation_lock_anim_pressed_off, k_button_scren_orientation_lock_anim_blink_off );
				m_buttonLock->SetText2( k_button_scren_orientation_lock_text2, k_button_scren_orientation_lock_font1, k_button_scren_orientation_lock_font2 );
			}
		}
		break;

	case action_select_language:
		{
			Transition_Start( transition_hide, action_select_language_trans );			
		}
		break;
	case action_select_language_trans:
		{
			GetParent()->SubMenu_Change( "Menu_LanguageSelection" );
		}
		break;

	case action_reset_profile:
		{
			m_menuConfirmation->SetConfirmationText( _TXT_ID(MENU_RESET_PROFILE_CONFIRMATION) );
			SubMenu_Change( "Menu_Confirmation" );
		}
		break;


	case action_back:
		{
			Transition_Start( transition_hide, action_back_trans );
		}
		break;
	case action_back_trans:
		{
			if ( m_isIngame ) 
				GetParent()->SubMenu_Change( "Menu_Ingame_Options" );
			else
				GetParent()->SubMenu_Change( "Menu_Options" );
		}
		break;



	}
}

