void Menu_HighScoresLevelList::Destroy()
{
	if (m_music_id != -1) 
		__MGR_SOUNDS()->stop( m_music_id );

	VisualControls_Free();
	m_isInitialized = false;
	
	// Destroy sub-menus
	//-------------------------------
	SubMenus_Destroy();

	FreeResources();
}

//---------------------------------------------------------------------------------------------------------
//---------------------------------------------------------------------------------------------------------
void Menu_HighScoresLevelList::Draw()
{
	if (!m_isInitialized) return;

	DrawBackground();

	// Draw controls
	//-------------------------------
	VisualControls_Draw();

	// change !!!
	(( MenuMain * ) GetParent())->GetTitle()->Draw();

	/// Draw submenu
	if( m_pCurrentSubMenu != NULL )
		m_pCurrentSubMenu->Draw();
}


//---------------------------------------------------------------------------------------------------------
//---------------------------------------------------------------------------------------------------------
void Menu_HighScoresLevelList::Update( float dt )
{
	if( !m_isInitialized )
		return;

	if (m_arrowUp->IsPressed())
		m_vpane->ScrollVertical(-1);
	
	if (m_arrowDown->IsPressed())
		m_vpane->ScrollVertical(1);

	IMenu::Update( dt );

	if (Transition_IsGoing())
		return;

	if( m_selected != -1 )
	{
		m_selected = -1;
		Transition_Start( transition_hide, action_transition );				
	}
}

