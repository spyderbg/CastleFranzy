void Menu_HighScoresLevelList::GainFocus()
{
	IMenu::GainFocus();

	CUserProfile profile = __PROFILE();

	/// Set unlocked levels
	array<int> daysPerLevel = getNumberOfDaysPerLevel();

	for ( int i = 0; i < daysPerLevel.size() - 1; i++ )
	{
		VisualControlGetByActionId( k_buttons_base_action + i )->SetEnabled( HasCampaignScore(profile, i) );
	}

	VisualControlGetByActionId( k_buttons_base_action + daysPerLevel.size() - 1 )->SetEnabled( HasEndlessScore(profile) );

	m_vpane->ReturnToStartPos();

	m_selected = -1;
}

