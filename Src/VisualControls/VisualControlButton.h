typedef enum {
	button_anim_normal = 0,
	button_anim_pressed,
	button_anim_blink,
	button_anim_disabled,

	button_anim_number
}eButtonAnimations;


//---------------------------------------------------------------------------------------------------------
// Visual control button
//---------------------------------------------------------------------------------------------------------
class VisualControlButton : public IVisualControl
{
public:
	VisualControlButton( int action_id, int control_id = -1, int click_sfx = SFX_MENU_SELECT );
	~VisualControlButton();

	void Draw();
	int  Update( float dt );

	void SetEnabled(bool is_enabled);
	void SetSelected(bool is_selected);

	void Reset();

	void SetAnimations(ASprite* sprite, int anims_num, ...);
	bool SetCurrentAnim(eButtonAnimations anim_type, bool loop = true);

	inline void	SetResetTEWhenDragOut(bool enabled)	{ m_TE_resetInputOnDragOut = enabled; }
	inline void	SetDisabledTextAlpha(int alpha)		{ m_disabledTextAlpha = alpha; }

	void SetKeepSelection(bool keep);

	inline bool	IsPressed() { return m_curr_anim == button_anim_pressed; }

protected:
	int					m_animations[button_anim_number];
	eButtonAnimations	m_curr_anim;

protected:
	bool					m_TE_resetInputOnDragOut;
	int						m_disabledTextAlpha;

	bool					m_keepSelection;
};


