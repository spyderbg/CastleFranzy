/// This struct contain all string IDs i a single enum
struct STRING_IDS	
{
	#define BEGIN_STRINGS	
	#define END_STRINGS															
	#define STRING_( VALUE, ID )	enum { ID = VALUE }

	#include "Autogenerated/FortressDefender_ID.hpp" 

	#undef BEGIN_STRINGS
	#undef END_STRINGS
	#undef STRING_
};

// this struct contain all strings in a map
struct STRING_SIDS
{
	static std::map< stringc , int > s_stringMap;

	STRING_SIDS() 
	{
		#define BEGIN_STRINGS	
		#define END_STRINGS	
		#define S_STRING_( ID , SID )  s_stringMap[SID] = ID; 
	
		#include "Autogenerated/FortressDefender_ID_string.hpp"
	
		#undef BEGIN_STRINGS
		#undef END_STRINGS
		#undef S_STRING_
	}

	~STRING_SIDS() 
	{
		s_stringMap.clear();
	}


	static int GetIDFromSID( stringc sid ) 
	{
		std::map< stringc , int >::iterator found; 
		found = s_stringMap.find( sid );
		if ( found != s_stringMap.end() )
			return found->second;
		else
		{
			DBG_ERROR( "ERROR ! no text with SID %s\n", sid );
			GX_ASSERT ( false );
			return -1;
		}
	}
};

