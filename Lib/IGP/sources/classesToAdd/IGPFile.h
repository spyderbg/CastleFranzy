class IGPIResourceReadI
{
public:

	IGPIResourceReadI()			{ Release(); };
	virtual ~IGPIResourceReadI()	{ Close(); };

	////////////////////////////////////////////////////////////
	virtual int Skip(s32 value)					{ return 0; };
	virtual int FetchData(void)					{ return 0; };
	////////////////////////////////////////////////////////////

	////////////////////////////////////////////////////////////
	virtual int Read(void *out_pData, u32 in_nSize)	= 0;

	inline s8	ReadS8()	{ s8  val; Read(&val, sizeof(s8));	return val; }
	inline s16	ReadS16()	{ s16 val; Read(&val, sizeof(s16)); return val; }
	inline s32	ReadS32()	{ s32 val; Read(&val, sizeof(s32)); return val; }

	inline u8	ReadU8()	{ u8  val; Read(&val, sizeof(u8));	return val; }
	inline u16	ReadU16()	{ u16 val; Read(&val, sizeof(u16)); return val; }
	inline u32	ReadU32()	{ u32 val; Read(&val, sizeof(u32)); return val; }
	//////////////////////////////////////////////////////////////

	inline u32 GetLength()	{ return m_ResourceLength; }

protected:

	virtual void Release();
	virtual void Close();

	u8		m_ResourceProps[RESOURCE_PROPS_BUFFER];
	u32		m_ResourceOffset;
	s32		m_ResourceSize;
	s32		m_ResourceLength;

	u8*		m_BufferStart;
	u8*		m_BufferEnd;
	u8*		m_BufferCrt;
};

