void OSReport ( const char* msg, ... )
{	
	char tmp[1024];
	va_list marker;
	va_start(marker, msg);
	memset(tmp, 0, 1024);
	vsprintf(tmp, msg, marker);
	va_end(marker);

	WCHAR wstr[1024];
	mbstowcs(wstr, tmp, 1024);
	OutputDebugStringW(wstr);
	return;
}

using namespace irr;
using namespace core;
using namespace io;

void printHelp()
{
	printf("Usage: ListSoundFiles <header file> <sound archive 1> ... <sound archive n> \n");
}

int main(int argc, char** argv)
{
	if(argc < 2)
	{
		printHelp();
		return -1;
	}

	FILE* fo = fopen(argv[1], "wt");

	if(!fo)
	{
		printf("ERROR: Could not open file: %s\n", argv[1]);
		return -1;
	}

	fprintf(fo, "//---------------------------------------------------------------------------------------------------------\n");
	fprintf(fo, "// Auto-generated file from ListSoundFiles.exe\n");
	fprintf(fo, "//---------------------------------------------------------------------------------------------------------\n");

	fprintf(fo, "#ifndef __AUTOGENERATED_SOUNDS_H_INCLUDED__\n");
	fprintf(fo, "#define __AUTOGENERATED_SOUNDS_H_INCLUDED__\n");
	fprintf(fo, "//---------------------------------------------------------------------------------------------------------\n");
	fprintf(fo, "//---------------------------------------------------------------------------------------------------------\n\n");
	//fprintf(fo, "\n");

	int fileIndex = 0;

	for(int i = 2; i < argc; i++)
	{
		CZipReader* zr = 0;

		IReadFile* file = irr::io::createReadFile(argv[i]);
		if (file)
		{
			zr = new CZipReader(file, false, true);

			file->drop();
		}

		if(zr)
		{
			for(int j = 0; j < zr->getFileCount(); j++)
			{
				stringc fileName = zr->getFileInfo(j)->simpleFileName;
				stringc fileName2 = fileName.subString(0, fileName.size() - 4);
				fileName2.make_upper();
				
				if (fileName != "") //prevent folders to appear as files 
				{
					//fprintf(fo,"#define %s %d\n", fileName2.c_str(), fileIndex++);
					fprintf(fo,"#define %-50s%d\n", fileName2.c_str(), fileIndex++);
				}
			}

			zr->drop();
		}
	}

	fprintf(fo, "\n");
	fprintf(fo, "//---------------------------------------------------------------------------------------------------------\n");
	fprintf(fo, "//---------------------------------------------------------------------------------------------------------\n");
	fprintf(fo, "#endif //__AUTOGENERATED_SOUNDS_H_INCLUDED__\n");


	fclose(fo);

	return 0;
}