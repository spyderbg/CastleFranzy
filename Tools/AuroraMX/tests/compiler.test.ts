const root = path.resolve("../..");

test("unknown named extension blocks survive edits and malformed trailing data is rejected", () => {
  const s = parseSprite(
    '{ VERSION 0001\nCUSTOM "named" {\nVALUE 3\nNESTED { VALUE 4 }\n}\nMODULES {}\nSPRITE_END }',
  );
  assert.equal(s.extras.length, 1);
  assert.match(s.extras[0], /NESTED/);
  assert.deepEqual(parseSprite(serializeSprite(s)), s);
  assert.throws(
    () => parseSprite("{ VERSION 0001 SPRITE_END } trailing"),
    /unexpected content/,
  );
});
const macros = (text: string) =>
  Object.fromEntries(
    [...text.matchAll(/^\s*#define\s+(\w+)\s+(\d+)/gm)].map((m) => [
      m[1],
      Number(m[2]),
    ]),
  );
test("all 29 project sprites round-trip and compile to the original game metadata", async () => {
  // Immutable hashes of the retired AuroraGT exports, before replacing game
  // resources with YAML. The legacy compiler remains available in the editor.
  const references = JSON.parse(await readFile(path.join(root,
    "tests/fixtures/sprites/legacy-metadata.json"), "utf8"));
  let count = 0,
    exact = 0,
    externalPayload = 0;
  for (const group of ["Fonts", "Ingame", "Menu"])
    for (const name of (
      await readdir(path.join(root, "Data/Sprites", group))
    ).filter((p) => p.endsWith(".sprite"))) {
      const sprite = parseSprite(
        decodeText(
          await readFile(path.join(root, "Data/Sprites", group, name)),
        ),
      );
      assert.deepEqual(validateSprite(sprite), [], name);
      assert.deepEqual(
        parseSprite(serializeSprite(sprite)),
        sprite,
        name + " text round-trip",
      );
      const actual = compileSprite(sprite);
      const reference = references[group + "/" + name];
      assert.equal(actual.length, reference.bytes, name + " metadata length");
      assert.equal(createHash("sha256").update(actual).digest("hex"), reference.sha256,
        name + " original binary bytes");
      if (reference.bytes === reference.exportBytes) exact++;
      else externalPayload++;
      count++;
    }
  assert.equal(count, 29);
  assert.equal(exact, 23);
  assert.equal(externalPayload, 6);
});
test("Sprites.sprcmd copies all 29 YAML files unchanged and preserves original ID values", async () => {
  const temp = await mkdtemp(path.join(os.tmpdir(), "auroramx-batch-"));
  try {
    const report = await batchExport(
      path.join(root, "Data/Sprites/Sprites.sprcmd"),
      temp,
    );
    assert.equal(report.sprites.length, 29);
    assert.equal(report.files.length, 32);
    for (const sprite of report.sprites) {
      assert.match(sprite.source, /\.yaml$/);
      assert.match(sprite.output, /\.yaml$/);
      assert.deepEqual(await readFile(sprite.output), await readFile(sprite.source));
    }
    assert.equal(report.files.some((p) => /\.(?:b)?sprite$/.test(p)), false);
    for (const group of ["Fonts", "Ingame", "Menu"])
      assert.deepEqual(
        macros(await readFile(path.join(temp, "bin", group + ".h"), "utf8")),
        macros(
          await readFile(
            path.join(root, "Src/Autogenerated", group + ".h"),
            "utf8",
          ),
        ),
        group + " IDs",
      );
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
});
test("YAML copy rejects binary output and path escapes before replacing any files", async () => {
  const temp = await mkdtemp(path.join(os.tmpdir(), "auroramx-copy-"));
  try {
    await writeFile(path.join(temp, "source.yaml"), await readFile(
      path.join(root, "tests/fixtures/sprites/dizzy_effect.yaml")));
    await mkdir(path.join(temp, "out"));
    const existing = path.join(temp, "out", "sprite.yaml");
    await writeFile(existing, "previous valid copy");
    for (const [target, error] of [["bad.bsprite", /YAML source and output/],
      ["../escape.yaml", /leaves the output directory/]] as const) {
      await writeFile(path.join(temp, "copy.sprcmd"),
        `Load("source.yaml")\nCopy("sprite.yaml")\nCopy("${target}")`);
      await assert.rejects(batchExport(path.join(temp, "copy.sprcmd"), path.join(temp, "out")), error);
      assert.equal(await readFile(existing, "utf8"), "previous valid copy");
      assert.deepEqual(await readdir(path.join(temp, "out")), ["sprite.yaml"]);
    }
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
});
test("edited sprite changes the binary export independently of the committed binaries", () => {
  const s = parseSprite(
    '{ VERSION 0001\nIMAGE 0 "atlas.png"\nMODULES { MD 0x1000 MD_IMAGE 0 1 2 30 40 }\nFRAME "idle" { 0x2000\nFM 0x1000 -10 -20 +FLIP_X\n}\nANIM "idle" { 0x3000\nAF 0x2000 2 0 0\n}\nSPRITE_END }',
  );
  const before = compileSprite(s);
  s.modules[0].values[3] = 35;
  s.frames[0].parts[0].x = -15;
  const after = compileSprite(s);
  assert.notDeepEqual(after, before);
  assert.equal(after.readUInt16LE(13), 35);
  assert.deepEqual(frameBounds(s, s.frames[0]), {
    x1: -15,
    y1: -20,
    x2: 20,
    y2: 20,
  });
});
test("parses Windows paths and escaped quotes, numeric flags, multiple rectangles and cp1252", () => {
  const text = decodeText(
    Buffer.from(
      '{ VERSION 0001\nIMAGE 0 ".\\atlas.tga" TRANSP 0xFF00FF\nMODULES { MD 0x1000 MD_IMAGE 0 0 0 2 3 "caf\xe9" }\nFRAME "a" { 0x2000\nRC -2 -3 5 6\nRC 1 2 3 4\nFM 0x1000 1 2 FLAGS 0x03\n} SPRITE_END }',
      "latin1",
    ),
  );
  const s = parseSprite(text);
  assert.equal(s.images[0].file, ".\\atlas.tga");
  assert.equal(s.modules[0].name, "café");
  assert.equal(s.frames[0].parts[0].flags, 3);
  assert.equal(s.frames[0].rects.length, 2);
  assert.deepEqual(parseSprite(serializeSprite(s)), s);
});
test("rejects missing references, cyclic hyperframes, out-of-range animation data and unsupported FFT layouts", async () => {
  const s = emptySprite();
  s.images = [{ id: 0, file: "a.png" }];
  s.modules = [
    { id: 4096, name: "", type: "MD_IMAGE", values: [0, 0, 0, 2, 2] },
  ];
  s.frames = [
    {
      id: 8192,
      name: "",
      rects: [],
      parts: [{ target: 999, x: 0, y: 0, flags: 0 }],
    },
  ];
  assert.throws(() => compileSprite(s), /Missing module/);
  s.frames[0].parts = [{ target: 8192, x: 0, y: 0, flags: 16 }];
  assert.throws(() => compileSprite(s), /Cyclic/);
  s.frames[0].parts = [{ target: 4096, x: 0, y: 0, flags: 0 }];
  s.animations = [
    {
      id: 12288,
      name: "",
      frames: [{ target: 8192, x: 128, y: 0, time: 1, flags: 0 }],
    },
  ];
  assert.throws(() => compileSprite(s), /8-bit/);
  const temp = await mkdtemp(path.join(os.tmpdir(), "auroramx-fft-"));
  try {
    await writeFile(
      path.join(temp, "bad.fft"),
      'FILE_FORMAT_TEMPLATE "different" {}',
    );
    await writeFile(path.join(temp, "bad.sprcmd"), 'InitBSpriteFFT("bad.fft")');
    await assert.rejects(
      batchExport(path.join(temp, "bad.sprcmd")),
      /different fields/,
    );
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
});
